/** 画面に表示し、練習結果として保存する自動評価。 */
export type ShapeEvaluation = {
  /** 形状4項目と、対象モードでは影を重み付きで合計した総合点（0〜100）。 */
  score: number;
  /** 見本線の再現と不要な描き足しを評価した輪郭点（0〜100）。 */
  outline: number;
  /** 対応する見本線と描画線の方向を評価した傾き点（0〜100）。 */
  angle: number;
  /** 外接矩形の幅と高さをそれぞれ比較した大きさ点（0〜100）。 */
  size: number;
  /** 外接矩形の縦横比を比較した比率点（0〜100）。 */
  proportion: number;
  /** 投影影の位置と広がりを評価した影点。影を評価しない場合はnull。 */
  shadow: number | null;
  /** 描画の中心を見本へ合わせるための水平移動量。マスクサイズに対する比率。 */
  alignmentX: number;
  /** 描画の中心を見本へ合わせるための垂直移動量。マスクサイズに対する比率。 */
  alignmentY: number;
  /** 最も改善の余地がある項目に応じた練習用メッセージ。 */
  feedback: string;
};
